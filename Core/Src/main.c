/* System state */
static robot_state_e robot_state = ROBOT_STOP;
static chassis_mode_e chassis_mode_request = CHASSIS_MODE_INDEPENDENT;

/* Timer handles (assumed to be initialized by CubeMX) */
extern TIM_HandleTypeDef htim6;  /* 1kHz control task timer */
extern TIM_HandleTypeDef htim7;  /* LED indicator timer */

/* LED breathing effect variables */
static uint32_t led1_breath_counter = 0;
static uint32_t led2_flash_counter = 0;
static const uint32_t LED1_BREATH_PERIOD = 2000; /* 2s breathing cycle */

